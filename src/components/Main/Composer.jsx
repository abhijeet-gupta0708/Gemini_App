import { useEffect, useRef } from "react";
import { ArrowUp, Sparkle, Stop } from "../Icons";
import { useMediaQuery } from "../../lib/useMediaQuery";
import { modelLabel } from "../../lib/format";

export default function Composer({ value, onChange, onSubmit, onStop, busy, focusKey, model }) {
  const ref = useRef(null);
  const finePointer = useMediaQuery("(pointer: fine)");

  useEffect(() => {
    const focus = () => ref.current?.focus();
    window.addEventListener("gemini:focus-composer", focus);
    return () => window.removeEventListener("gemini:focus-composer", focus);
  }, []);

  useEffect(() => {
    const el = ref.current;
    if (!el) return;
    el.style.height = "auto";
    el.style.height = `${Math.min(el.scrollHeight, 216)}px`;
  }, [value]);

  useEffect(() => {
    if (finePointer) ref.current?.focus();
  }, [focusKey, finePointer]);

  const submit = () => {
    if (busy || !value.trim()) return;
    onSubmit(value);
  };

  const handleKeyDown = (event) => {
    if (event.key === "Enter" && !event.shiftKey && !event.nativeEvent.isComposing) {
      event.preventDefault();
      submit();
    }
  };

  return (
    <div className="composer">
      <div className="composer__field">
        <label htmlFor="composer-input" className="visually-hidden">
          Message Gemini
        </label>
        <textarea
          ref={ref}
          id="composer-input"
          rows={1}
          value={value}
          onChange={(event) => onChange(event.target.value)}
          onKeyDown={handleKeyDown}
          placeholder="Ask Gemini anything…"
          spellCheck="true"
          autoComplete="off"
        />
      </div>

      <div className="composer__bar">
        <span className="composer__model" title={`Replies are generated by ${model || "the Gemini API"}`}>
          <Sparkle size={13} />
          {modelLabel(model)}
        </span>

        {busy ? (
          <button
            type="button"
            className="send send--stop"
            onClick={onStop}
            aria-label="Stop generating"
            title="Stop generating"
          >
            <Stop size={15} />
          </button>
        ) : (
          <button
            type="button"
            className="send"
            onClick={submit}
            disabled={!value.trim()}
            aria-label="Send message"
            title="Send message"
          >
            <ArrowUp size={18} strokeWidth={2.1} />
          </button>
        )}
      </div>
    </div>
  );
}
